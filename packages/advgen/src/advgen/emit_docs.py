# ------------------------------------------------------------------ helpers
def logical_domain(c: Column) -> str:
    n, t = c.name, c.pg_type
    if c.is_pk:
        return "Identifier"
    if c.ref:
        return "Identifier"
    if c.code_set or any(ch.kind == "in" for ch in c.checks):
        return "Code"
    if t == "char(3)":
        return "Currency Code" if "currency" in n else "ISO Code"
    if t == "timestamptz":
        return "Timestamp"
    if t == "date":
        return "Date"
    if t == "boolean":
        return "Indicator"
    if t in ("integer", "bigint"):
        return "Quantity"
    if t.startswith("numeric"):
        if re.search(r"(_pct|_percent|_percentage)$", n):
            return "Percentage"
        if re.search(r"(rate|ratio|score|weight|threshold|accuracy)", n):
            return "Rate"
        if re.search(r"(amount|cost|price|spend|budget|fee|value|revenue|cpm|cpc|cpa)", n):
            return "Amount"
        return "Decimal"
    if re.search(r"(email)", n):
        return "Email"
    if re.search(r"(_url|url$)", n):
        return "URL"
    if n.endswith(("_name", "_title")) or n in ("title", "name"):
        return "Name"
    if re.search(r"(_code|_number|_ref|_reference|_key)$", n):
        return "Business Code"
    return "Text"


def short(text: str, n: int = 180) -> str:
    text = " ".join(text.split())
    first = re.split(r"(?<=[.!?])\s", text, maxsplit=1)[0]
    out = first if len(first) <= n else first[: n - 1].rstrip() + "…"
    return out.replace("|", "\\|")


def md_escape(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def key_flags(t: Table, c: Column) -> str:
    flags = []
    if c.name in t.pk_columns:
        flags.append("PK")
    if c.ref:
        flags.append("FK" if c.ref.enforced else "SOFT")
    if any(c.name in u for u in t.uniques):
        flags.append("UK")
    return ", ".join(flags)


def constraints_text(t: Table, c: Column) -> str:
    parts = [check_expr(c.name, ch) for ch in c.checks]
    if c.code_set:
        parts.append(f"→ ref.{c.code_set}")
    if c.ref:
        tgt = f"{c.ref.target_database}.{c.ref.target_fqn}" if not c.ref.enforced else c.ref.target_fqn
        parts.append(f"→ {tgt}" + ("" if c.ref.enforced else " (not enforced)"))
    for s, e in t.date_pairs:
        if c.name == e:
            parts.append(f"{e} >= {s}")
    return "; ".join(parts)


def dbml_str(text: str) -> str:
    return "'" + " ".join(text.split()).replace("\\", "\\\\").replace("'", "\\'") + "'"


# --------------------------------------------------------------------- DBML
def emit_dbml(model: Model, s: System, path: Path) -> None:
    out = [f"// {s.database}: {s.mimics}. {LOGICAL_NOTE}\n\n",
           f"Project {s.database} {{\n  database_type: 'PostgreSQL'\n  Note: {dbml_str(s.description)}\n}}\n\n"]
    for cs in s.code_sets.values():
        out.append(f"Table ref.{cs.name} [note: {dbml_str('Code set. Values: ' + ', '.join(cs.values))}] {{\n"
                   f"  code text [pk]\n  label text [not null]\n  description text\n"
                   f"  sort_order integer [not null, default: 0]\n  is_active boolean [not null, default: true]\n}}\n\n")
    for t in s.tables:
        out.append(f"Table {t.fqn} [note: {dbml_str(t.description)}] {{\n")
        single_pk = len(t.pk_columns) == 1
        for c in t.columns:
            settings = []
            if single_pk and c.is_pk:
                settings.append("pk")
            if not c.nullable:
                settings.append("not null")
            if c.default is not None:
                settings.append(f"default: {c.default}" if c.default in ("false", "true") else f"default: `{c.default}`")
            note = c.description
            cons = constraints_text(t, c)
            if cons:
                note += f" [{cons}]"
            settings.append(f"note: {dbml_str(note)}")
            out.append(f"  {c.name} {c.pg_type.replace(' ', '')} [{', '.join(settings)}]\n")
        idx = []
        if not single_pk:
            idx.append(f"    ({', '.join(t.pk_columns)}) [pk]\n")
        for u in t.uniques:
            idx.append(f"    ({', '.join(u)}) [unique]\n")
        if idx:
            out.append("\n  indexes {\n" + "".join(idx) + "  }\n")
        out.append("}\n\n")
    for t in s.tables:
        for c in t.columns:
            if c.code_set:
                out.append(f"Ref: {t.fqn}.{c.name} > ref.{c.code_set}.code\n")
            elif c.ref and c.ref.enforced:
                out.append(f"Ref: {t.fqn}.{c.name} > {c.ref.target_fqn}.{c.ref.target_column}\n")
    out.append("\n")
    for sc in s.schemas:
        out.append(f"TableGroup {sc} {{\n" + "".join(f"  {t.fqn}\n" for t in s.tables if t.schema == sc) + "}\n\n")
    out.append("TableGroup ref {\n" + "".join(f"  ref.{n}\n" for n in s.code_sets) + "}\n")
    path.write_text("".join(out))


# ------------------------------------------------------------------ Mermaid
def mermaid_physical(s: System, tables: list[Table]) -> str:
    names = {t.fqn for t in tables}
    lines = ["erDiagram"]
    rels = []
    for t in tables:
        attrs = []
        for c in t.columns:
            flags = key_flags(t, c)
            if not flags:
                continue
            comment = ""
            if c.ref and not c.ref.enforced:
                comment = f' "soft ref {c.ref.target_database}.{c.ref.target_table}"'
            mtype = re.sub(r"[^A-Za-z0-9_]", "_", c.pg_type).strip("_")
            attrs.append(f"        {mtype} {c.name} {flags.replace('SOFT', 'FK')}{comment}")
            if c.ref and c.ref.enforced:
                rels.append((c.ref.target_table, t.name, c))
        lines.append(f"    {t.name} {{")
        lines += attrs
        lines.append("    }")
    for parent, child, c in rels:
        left = "||" if not c.nullable else "|o"
        lines.append(f"    {parent} {left}--o{{ {child} : \"{c.name}\"")
    return "\n".join(lines)


def emit_physical_erd(model: Model, s: System, path: Path) -> None:
    out = [f"# {s.database}: physical ERD\n\n{LOGICAL_NOTE}\n\n",
           f"**System:** {s.mimics}. **Instance:** `{s.service}` (port {s.port}).\n\n",
           "Diagrams show key columns only: **PK**, **FK** (enforced), **UK** and soft references "
           "(labelled `soft ref`, unenforced cross-system or partitioned-target references). "
           "Lookup FKs to `ref.*` are omitted for legibility; see the data dictionary.\n\n"]
    for sc, sub in s.subdomains():
        tables = [t for t in s.tables if t.schema == sc and t.subdomain == sub]
        out.append(f"## {sc}.{sub}\n\n```mermaid\n{mermaid_physical(s, tables)}\n```\n\n")
    soft = [(t, c) for t in s.tables for c in t.columns if c.ref and not c.ref.enforced]
    out.append(f"## Soft references ({len(soft)})\n\n| From | To | Nullable | Reason |\n|---|---|---|---|\n")
    for t, c in soft:
        out.append(f"| `{t.fqn}.{c.name}` | `{c.ref.target_database}.{c.ref.target_fqn}` | "
                   f"{'yes' if c.nullable else 'no'} | {c.ref.reason.replace('_', ' ')} |\n")
    path.write_text("".join(out))


def mermaid_logical(model: Model, tables: list[Table]) -> str:
    inside = {t.key for t in tables}
    lines = ["erDiagram"]
    rels = []
    for t in tables:
        lines.append(f"    {t.name} {{")
        for c in t.columns:
            if c.is_pk:
                lines.append(f"        Identifier {c.name} PK")
            elif c.ref:
                system = model.systems[c.ref.target_system]
                note = "" if c.ref.target_system == t.system else f' "owned by {system.database}"'
                lines.append(f"        Identifier {c.name} FK{note}")
                rels.append((c.ref.target_table, t.name, c))
        lines.append("    }")
    for parent, child, c in rels:
        left = "||" if not c.nullable else "|o"
        lines.append(f"    {parent} {left}--o{{ {child} : \"{c.name}\"")
    return "\n".join(lines)


# ----------------------------------------------------------- logical model
def emit_logical(model: Model, s: System, path: Path) -> None:
    out = [f"# Logical model: {s.database}\n\n{LOGICAL_NOTE}\n\n",
           f"**Source system role:** {s.mimics}. {s.description.strip()}\n\n",
           "The logical model is technology-neutral: entities, business attributes with logical domains, "
           "optionality, keys and every business relationship, **including relationships to entities owned "
           "by other systems** (marked *owned by …*). How each relationship is physically implemented "
           "(enforced FK vs soft reference) is decided in the physical model.\n\n",
           "## Contents\n\n"]
    for sc, sub in s.subdomains():
        out.append(f"- [{sc}.{sub}](#{sc}{sub})\n")
    out.append("- [Code sets](#code-sets)\n- [Normalization notes](#normalization-notes)\n\n")
    for sc, sub in s.subdomains():
        tables = [t for t in s.tables if t.schema == sc and t.subdomain == sub]
        out.append(f"## {sc}.{sub}\n\n| Entity | Kind | Definition |\n|---|---|---|\n")
        for t in tables:
            out.append(f"| [{t.name}](#{t.name}) | {t.data_type.replace('_data', '')} | {short(t.description, 220)} |\n")
        out.append(f"\n```mermaid\n{mermaid_logical(model, tables)}\n```\n\n")
        for t in tables:
            out.append(f"### {t.name}\n\n{md_escape(t.description)}\n\n")
            ids = [", ".join(u) for u in t.uniques]
            out.append(f"**Primary identifier:** `{t.pk.name}`"
                       + (f". **Business key(s):** {'; '.join(f'`{i}`' for i in ids)}" if ids else "") + "\n\n")
            out.append("| Attribute | Business name | Domain | Opt. | Key | Definition |\n|---|---|---|---|---|---|\n")
            for c in t.columns:
                key = key_flags(t, c).replace("SOFT", "FK")
                bname = c.glossary or c.name.replace("_", " ").title()
                if c.ref:
                    target = f"{c.ref.target_table}" + ("" if c.ref.target_system == t.system
                                                        else f" ({model.systems[c.ref.target_system].database})")
                    domain = f"Identifier → {target}"
                elif c.code_set:
                    domain = f"Code ({c.code_set})"
                else:
                    domain = logical_domain(c)
                out.append(f"| `{c.name}` | {md_escape(bname)} | {domain} | {'O' if c.nullable else 'M'} | {key} | {short(c.description)} |\n")
            out.append("\n")
    out.append("## Code sets\n\nEnumerated domains promoted to reference entities (one per column name in this system):\n\n"
               "| Code set | Values | Used by |\n|---|---|---|\n")
    for cs in s.code_sets.values():
        out.append(f"| `{cs.name}` | {', '.join(cs.values)} | {', '.join(f'{k.split('.')[1]}.{c}' for k, c in cs.usages)} |\n")
    selfs = [(t, c) for t in s.tables for c in t.columns if c.ref and c.ref.target_table == t.name]
    inbound = Counter(model.systems[t.system].database for t in model.tables.values() for c in t.columns
                      if c.ref and c.ref.target_system == s.key and t.system != s.key)
    outbound = Counter(c.ref.target_database for t in s.tables for c in t.columns
                       if c.ref and c.ref.target_system != s.key)
    out.append("\n## Normalization notes\n\n"
               "- Enumerated values are separate code-set entities rather than free text "
               f"({len(s.code_sets)} code sets); other bounded value lists stay as attribute domains (CHECK in the physical model).\n"
               "- Each entity has a single surrogate identifier; business keys are kept as alternate keys.\n"
               "- The MVM's attribute depth is preserved deliberately: it is denormalised for analytics "
               "(e.g. names copied from related entities, pre-computed rates). These attributes are kept for lineage "
               "with the lakehouse and documented in the data dictionary; they are candidates for removal in a "
               "stricter 3NF iteration.\n")
    if selfs:
        out.append("- Recursive relationships (hierarchies, revisions): "
                   + ", ".join(f"`{t.name}.{c.name}`" for t, c in selfs) + ".\n")
    out.append(f"- Relationships to other systems: outbound {dict(outbound)}; inbound {dict(inbound)}.\n")
    path.write_text("".join(out))


# ------------------------------------------------------- dictionary & maps
DICT_FIELDS = ["database", "schema", "table", "column", "ordinal", "pg_type", "logical_domain", "nullable",
               "default", "keys", "references", "ref_enforced", "ref_reason", "code_set", "checks",
               "not_null_reason", "pii_tags", "business_name", "description", "origin",
               "mvm_domain", "mvm_product", "mvm_column", "mvm_type"]


def dictionary_rows(model: Model) -> list[dict]:
    rows = []
    for s in model.systems.values():
        for cs in s.code_sets.values():
            for i, (n, ty, nn, d) in enumerate([("code", "text", False, "Code value (primary key)."),
                                                ("label", "text", False, "Display label."),
                                                ("description", "text", True, "Optional longer description."),
                                                ("sort_order", "integer", False, "Display order."),
                                                ("is_active", "boolean", False, "False hides the code from new data entry."),
                                                ("created_at", "timestamptz", False, "Audit."), ("created_by", "text", False, "Audit."),
                                                ("updated_at", "timestamptz", False, "Audit."), ("updated_by", "text", False, "Audit.")], 1):
                rows.append({"database": s.database, "schema": "ref", "table": cs.name, "column": n, "ordinal": i,
                             "pg_type": ty, "nullable": "Y" if nn else "N", "keys": "PK" if n == "code" else "",
                             "description": d, "origin": "code_set",
                             "business_name": n.replace("_", " ").title()})
        for t in s.tables:
            for i, c in enumerate(t.columns, 1):
                checks = [check_expr(c.name, ch) for ch in c.checks]
                checks += [f"{e} >= {st}" for st, e in t.date_pairs if e == c.name]
                rows.append({
                    "database": s.database, "schema": t.schema, "table": t.name, "column": c.name, "ordinal": i,
                    "pg_type": c.pg_type, "logical_domain": logical_domain(c), "nullable": "Y" if c.nullable else "N",
                    "default": c.default or "", "keys": key_flags(t, c),
                    "references": (f"{c.ref.target_database}.{c.ref.target_fqn}.{c.ref.target_column}" if c.ref
                                   else f"{s.database}.ref.{c.code_set}.code" if c.code_set else ""),
                    "ref_enforced": ("Y" if c.ref.enforced else "N") if c.ref else ("Y" if c.code_set else ""),
                    "ref_reason": c.ref.reason if c.ref else ("code_set" if c.code_set else ""),
                    "code_set": c.code_set or "", "checks": "; ".join(checks), "not_null_reason": c.not_null_reason,
                    "pii_tags": c.tags, "business_name": c.glossary or c.name.replace("_", " ").title(),
                    "description": " ".join(c.description.split()), "origin": c.origin,
                    "mvm_domain": c.mvm["domain"] if c.mvm else "", "mvm_product": c.mvm["product"] if c.mvm else "",
                    "mvm_column": c.mvm_name, "mvm_type": c.mvm["type"] if c.mvm else ""})
    return rows


def write_csv(path: Path, fields: list[str], rows: list[dict]) -> None:
    with path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for r in rows:
            w.writerow({k: r.get(k, "") for k in fields})


def emit_dictionary_md(model: Model, s: System, path: Path) -> None:
    out = [f"# Data dictionary: {s.database}\n\n{LOGICAL_NOTE}\n\n",
           f"{s.mimics}. {len(s.tables)} tables, {sum(len(t.columns) for t in s.tables)} columns, "
           f"{len(s.code_sets)} code sets. Machine-readable version: [data_dictionary.csv](data_dictionary.csv).\n\n",
           "Keys: **PK** primary key, **FK** enforced foreign key, **SOFT** unenforced logical reference, **UK** unique business key. "
           "**Null** N = NOT NULL.\n\n"]
    for sc in s.schemas:
        out.append(f"## Schema `{sc}`\n\n")
        for t in [t for t in s.tables if t.schema == sc]:
            part = f" Partitioned by RANGE (`{t.partition_key}`), monthly." if t.partition_key else ""
            out.append(f"### `{t.fqn}`\n\n{md_escape(t.description)}{part}\n\n"
                       "| # | Column | Type | Null | Default | Keys | Constraints / references | Description |\n"
                       "|---|---|---|---|---|---|---|---|\n")
            for i, c in enumerate(t.columns, 1):
                out.append(f"| {i} | `{c.name}` | {c.pg_type} | {'Y' if c.nullable else 'N'} | {c.default or ''} | "
                           f"{key_flags(t, c)} | {md_escape(constraints_text(t, c))} | {md_escape(c.description)} |\n")
            out.append("\n")
    out.append("## Schema `ref` (code sets)\n\n| Table | Codes |\n|---|---|\n")
    for cs in s.code_sets.values():
        out.append(f"| `ref.{cs.name}` | {', '.join(f'`{v}`' for v in cs.values)} |\n")
    path.write_text("".join(out))


def emit_mappings(model: Model, root: Path) -> None:
    rows = []
    for t in model.tables.values():
        s = model.systems[t.system]
        for c in t.columns:
            if not c.mvm:
                continue
            m = c.mvm
            rows.append({"mvm_domain": m["domain"], "mvm_subdomain": m["subdomain"], "mvm_product": m["product"],
                         "mvm_column": m["column_name"], "mvm_type": m["type"], "mvm_foreign_key_to": m["foreign_key_to"],
                         "target_database": s.database, "target_schema": t.schema, "target_table": t.name,
                         "target_column": c.name, "target_type": c.pg_type,
                         "transform": "; ".join(c.notes) or "as is"})
    fields = list(rows[0])
    write_csv(root / "mapping" / "mvm_to_oltp_mapping.csv", fields, rows)
    refs = []
    for t in model.tables.values():
        s = model.systems[t.system]
        for c in t.columns:
            if c.ref and not c.ref.enforced:
                refs.append({"from_database": s.database, "from_table": t.fqn, "from_column": c.name,
                             "nullable": "Y" if c.nullable else "N", "to_database": c.ref.target_database,
                             "to_table": c.ref.target_fqn, "to_column": c.ref.target_column, "reason": c.ref.reason})
    write_csv(root / "mapping" / "cross_system_refs.csv", list(refs[0]), refs)


def emit_decision_log(model: Model, root: Path) -> None:
    by_cat = defaultdict(list)
    for d in model.decisions:
        by_cat[d.category].append(d)
    refs = [c for t in model.tables.values() for c in t.columns if c.ref]
    n_fk = sum(1 for c in refs if c.ref.enforced and c.origin != "added")
    n_soft = sum(1 for c in refs if not c.ref.enforced and c.origin != "added")
    added_fk = ", ".join(f"`{c.name}`" for c in refs if c.ref.enforced and c.origin == "added")
    added_soft = ", ".join(f"`{c.name}`" for c in refs if not c.ref.enforced and c.origin == "added")
    n_mvm_fk = sum(1 for r in model.mvm_rows if r["foreign_key_to"])
    out = [(root / "mapping" / "decision_log.header.md").read_text(),
           "\n## Generated: transformation summary\n\n",
           f"| Metric | Value |\n|---|---|\n",
           f"| MVM tables / columns | 95 / {len(model.mvm_rows)} |\n",
           f"| OLTP tables / columns (excluding `ref`) | {len(model.tables)} / {sum(len(t.columns) for t in model.tables.values())} |\n",
           f"| Code sets (`ref.*` tables) | {sum(len(s.code_sets) for s in model.systems.values())} |\n",
           f"| MVM relationships | {n_mvm_fk} |\n",
           f"| → enforced FKs (same system) | {n_fk} (plus added: {added_fk}) |\n",
           f"| → soft references | {n_soft} (plus added: {added_soft}) |\n",
           f"| Columns NOT NULL | {sum(1 for t in model.tables.values() for c in t.columns if not c.nullable)} |\n",
           f"| CHECK constraints | {sum(len(c.checks) for t in model.tables.values() for c in t.columns) + sum(len(t.date_pairs) for t in model.tables.values())} |\n",
           f"| Unique business keys | {sum(len(t.uniques) for t in model.tables.values())} |\n\n"]
    titles = {"defect_fix": "Defect fixes", "type": "Type overrides", "partitioning": "Partitioning",
              "soft_ref": "Same-system references not enforced", "code_set": "Shared code sets (union of values)",
              "audit": "Audit column collisions", "nullability": "Parent references forced nullable"}
    for cat, title in titles.items():
        items = by_cat.get(cat)
        if not items:
            continue
        out.append(f"## Generated: {title}\n\n| Target | Decision | Reason |\n|---|---|---|\n")
        for d in items:
            out.append(f"| `{d.target}` | {md_escape(d.decision)} | {md_escape(d.reason)} |\n")
        out.append("\n")
    (root / "mapping" / "decision_log.md").write_text("".join(out))


def emit(model: Model, root: Path) -> None:
    (root / "models" / "logical").mkdir(parents=True, exist_ok=True)
    (root / "dictionary").mkdir(exist_ok=True)
    (root / "mapping").mkdir(exist_ok=True)
    for s in model.systems.values():
        phys = root / "models" / "physical" / s.database
        emit_dbml(model, s, phys / f"{s.database}.dbml")
        emit_physical_erd(model, s, phys / "erd.md")
        emit_logical(model, s, root / "models" / "logical" / f"{s.database}.md")
        emit_dictionary_md(model, s, root / "dictionary" / f"{s.database}.md")
    write_csv(root / "dictionary" / "data_dictionary.csv", DICT_FIELDS, dictionary_rows(model))
    emit_mappings(model, root)
    emit_decision_log(model, root)
