"""PostgreSQL DDL emitter: one ordered script set per source system."""
from __future__ import annotations

import hashlib
from pathlib import Path

from .model import Check, Column, Model, System, Table

MAX_IDENT = 63
HEADER = "-- Generated by advgen from the Advertising MVM ({sha}). Do not edit by hand.\n-- System: {db} ({mimics})\n\n"


def ident(prefix: str, table: str, *parts: str) -> str:
    name = f"{prefix}_{table}__{'_'.join(parts)}" if parts else f"{prefix}_{table}"
    if len(name) <= MAX_IDENT:
        return name
    digest = hashlib.sha1(name.encode()).hexdigest()[:8]
    return f"{name[:MAX_IDENT - 9]}_{digest}"


def lit(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def check_expr(col: str, ch: Check) -> str:
    if ch.kind == "in":
        return f"{col} IN ({', '.join(lit(v) for v in ch.values)})"
    if ch.kind == "regex":
        return f"{col} ~ {lit(ch.pattern)}"
    if ch.max is not None:
        return f"{col} BETWEEN {ch.min:g} AND {ch.max:g}"
    return f"{col} >= {ch.min:g}"


def column_sql(c: Column) -> str:
    parts = [f"    {c.name} {c.pg_type}"]
    if not c.nullable:
        parts.append("NOT NULL")
    if c.default is not None:
        parts.append(f"DEFAULT {c.default}")
    return " ".join(parts)


def table_constraints(t: Table) -> list[str]:
    out = [f"    CONSTRAINT {ident('pk', t.name)} PRIMARY KEY ({', '.join(t.pk_columns)})"]
    for cols in t.uniques:
        out.append(f"    CONSTRAINT {ident('uq', t.name, *cols)} UNIQUE ({', '.join(cols)})")
    for c in t.columns:
        for i, ch in enumerate(c.checks):
            suffix = (c.name,) if i == 0 else (c.name, str(i + 1))
            out.append(f"    CONSTRAINT {ident('ck', t.name, *suffix)} CHECK ({check_expr(c.name, ch)})")
    for start, end in t.date_pairs:
        out.append(f"    CONSTRAINT {ident('ck', t.name, end, 'ge', start)} CHECK ({end} >= {start})")
    return out


def create_table(t: Table) -> str:
    body = ",\n".join([column_sql(c) for c in t.columns] + table_constraints(t))
    tail = f" PARTITION BY RANGE ({t.partition_key})" if t.partition_key else ""
    return f"CREATE TABLE {t.fqn} (\n{body}\n){tail};\n"


def create_ref_table(name: str) -> str:
    return (f"CREATE TABLE ref.{name} (\n"
            f"    code text NOT NULL,\n"
            f"    label text NOT NULL,\n"
            f"    description text,\n"
            f"    sort_order integer NOT NULL DEFAULT 0,\n"
            f"    is_active boolean NOT NULL DEFAULT true,\n"
            f"    created_at timestamptz NOT NULL DEFAULT now(),\n"
            f"    created_by text NOT NULL DEFAULT audit.current_actor(),\n"
            f"    updated_at timestamptz NOT NULL DEFAULT now(),\n"
            f"    updated_by text NOT NULL DEFAULT audit.current_actor(),\n"
            f"    CONSTRAINT {ident('pk', 'ref_' + name)} PRIMARY KEY (code)\n"
            f");\n")


AUDIT_FUNCTIONS = """\
CREATE OR REPLACE FUNCTION audit.current_actor() RETURNS text
LANGUAGE sql STABLE AS $$
    SELECT COALESCE(NULLIF(current_setting('app.actor', true), ''), current_user::text)
$$;
COMMENT ON FUNCTION audit.current_actor() IS 'Acting user: session setting app.actor (set by the application) or the database role.';

CREATE OR REPLACE FUNCTION audit.set_updated() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.created_at := OLD.created_at;
    NEW.created_by := OLD.created_by;
    NEW.updated_at := statement_timestamp();
    NEW.updated_by := audit.current_actor();
    RETURN NEW;
END
$$;
COMMENT ON FUNCTION audit.set_updated() IS 'BEFORE UPDATE row trigger: keeps created_* immutable and maintains updated_*.';
"""

PARTITION_FUNCTION = """\
CREATE OR REPLACE FUNCTION util.ensure_monthly_partitions(parent regclass, first_month date, months integer)
RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    nsp text;
    rel text;
    m date;
BEGIN
    SELECT n.nspname, c.relname INTO nsp, rel
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE c.oid = parent;
    FOR i IN 0 .. months - 1 LOOP
        m := (date_trunc('month', first_month) + make_interval(months => i))::date;
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS %I.%I PARTITION OF %s FOR VALUES FROM (%L) TO (%L)',
            nsp, rel || '_p' || to_char(m, 'YYYYMM'), parent, m, (m + interval '1 month')::date);
    END LOOP;
    EXECUTE format('CREATE TABLE IF NOT EXISTS %I.%I PARTITION OF %s DEFAULT', nsp, rel || '_pdefault', parent);
END
$$;
COMMENT ON FUNCTION util.ensure_monthly_partitions(regclass, date, integer) IS
    'Creates monthly range partitions (<table>_pYYYYMM) and a default partition. Schedule monthly to stay ahead of incoming events.';
"""


def emit_system(model: Model, s: System, out: Path, window: tuple[str, int]) -> list[str]:
    ddl = out / "ddl"
    ddl.mkdir(parents=True, exist_ok=True)
    head = HEADER.format(sha=model.source_sha[:12], db=s.database, mimics=s.mimics)
    partitioned = [t for t in s.tables if t.partition_key]
    files: dict[str, str] = {}

    files["000_database.sql"] = head + (
        f"-- Run against the maintenance database (postgres) of instance {s.service}.\n"
        f"CREATE DATABASE {s.database}\n    ENCODING 'UTF8'\n    TEMPLATE template0\n"
        f"    LOCALE_PROVIDER builtin\n    BUILTIN_LOCALE 'C.UTF-8';\n\n"
        f"COMMENT ON DATABASE {s.database} IS {lit(s.mimics + ' source system. ' + s.description.strip())};\n")

    schemas = ["audit", "ref"] + (["util"] if partitioned else []) + s.schemas
    sql = [head]
    for sc in schemas:
        sql.append(f"CREATE SCHEMA IF NOT EXISTS {sc};\n")
    sql.append("\n" + AUDIT_FUNCTIONS)
    if partitioned:
        sql.append("\n" + PARTITION_FUNCTION)
    files["010_schemas_extensions.sql"] = "".join(sql)

    files["020_ref_tables.sql"] = head + "\n".join(create_ref_table(n) for n in s.code_sets)
    files["030_tables.sql"] = head + "\n".join(create_table(t) for t in s.tables)

    fks = [head]
    for t in s.tables:
        for c in t.columns:
            if c.code_set:
                fks.append(f"ALTER TABLE {t.fqn} ADD CONSTRAINT {ident('fk', t.name, c.name)} "
                           f"FOREIGN KEY ({c.name}) REFERENCES ref.{c.code_set} (code) ON UPDATE CASCADE ON DELETE RESTRICT;\n")
            elif c.ref and c.ref.enforced:
                fks.append(f"ALTER TABLE {t.fqn} ADD CONSTRAINT {ident('fk', t.name, c.name)} "
                           f"FOREIGN KEY ({c.name}) REFERENCES {c.ref.target_fqn} ({c.ref.target_column}) ON DELETE RESTRICT;\n")
    files["040_constraints_fk.sql"] = "".join(fks)

    idx = [head]
    for t in s.tables:
        leading = {t.pk_columns[0]} | {u[0] for u in t.uniques}
        if t.partition_key:
            idx.append(f"CREATE INDEX {ident('brin', t.name, t.partition_key)} ON {t.fqn} USING brin ({t.partition_key});\n")
        for c in t.columns:
            if c.ref and c.name not in leading:
                kind = "" if c.ref.enforced else f" -- soft ref -> {c.ref.target_database}.{c.ref.target_fqn}"
                idx.append(f"CREATE INDEX {ident('ix', t.name, c.name)} ON {t.fqn} ({c.name});{kind}\n")
    files["050_indexes.sql"] = "".join(idx)

    if partitioned:
        start, months = window
        calls = "".join(f"    PERFORM util.ensure_monthly_partitions({lit(t.fqn)}::regclass, DATE {lit(start)}, {months});\n"
                        for t in partitioned)
        files["060_partitions.sql"] = head + f"DO $$\nBEGIN\n{calls}END\n$$;\n"

    trg = [head]
    for name in s.code_sets:
        trg.append(f"CREATE TRIGGER trg_audit BEFORE UPDATE ON ref.{name} FOR EACH ROW EXECUTE FUNCTION audit.set_updated();\n")
    for t in s.tables:
        trg.append(f"CREATE TRIGGER trg_audit BEFORE UPDATE ON {t.fqn} FOR EACH ROW EXECUTE FUNCTION audit.set_updated();\n")
    files["070_triggers.sql"] = "".join(trg)

    seed = [head]
    for cs in s.code_sets.values():
        rows = ",\n".join(f"    ({lit(v)}, {lit(cs.labels[v])}, {(i + 1) * 10})" for i, v in enumerate(cs.values))
        seed.append(f"INSERT INTO ref.{cs.name} (code, label, sort_order) VALUES\n{rows}\nON CONFLICT (code) DO NOTHING;\n\n")
    files["080_ref_seed.sql"] = "".join(seed)

    files["090_comments.sql"] = head + comments(model, s)

    for name, text in files.items():
        (ddl / name).write_text(text)
    return sorted(files)


def comments(model: Model, s: System) -> str:
    out = [f"COMMENT ON SCHEMA audit IS 'Audit helpers (actor resolution, updated_* trigger).';\n",
           f"COMMENT ON SCHEMA ref IS 'Lookup tables (code sets) promoted from MVM enum candidates.';\n"]
    for sc in s.schemas:
        out.append(f"COMMENT ON SCHEMA {sc} IS {lit('MVM domain ' + sc + ' as owned by ' + s.database + '.')};\n")
    for cs in s.code_sets.values():
        used = ", ".join(f"{k}.{c}" for k, c in cs.usages)
        out.append(f"COMMENT ON TABLE ref.{cs.name} IS {lit(f'Code set {cs.name}. Used by: {used}.')};\n")
    for t in s.tables:
        out.append(f"\nCOMMENT ON TABLE {t.fqn} IS {lit(t.description)};\n")
        for c in t.columns:
            out.append(f"COMMENT ON COLUMN {t.fqn}.{c.name} IS {lit(column_comment(c))};\n")
    return "".join(out)


def column_comment(c: Column) -> str:
    text = c.description
    if c.code_set:
        text += f" Code set: ref.{c.code_set}."
    if c.ref and not c.ref.enforced:
        why = {"cross_system": "cross-system", "partitioned_target": "partitioned target"}[c.ref.reason]
        text += (f" LOGICAL REF -> {c.ref.target_database}.{c.ref.target_fqn}.{c.ref.target_column}"
                 f" (not enforced: {why}).")
    if c.mvm and c.origin == "renamed":
        text += f" MVM column: {c.mvm_name}."
    return text.strip()


def emit(model: Model, root: Path, window: tuple[str, int]) -> None:
    for s in model.systems.values():
        emit_system(model, s, root / "models" / "physical" / s.database, window)


def manifest(model: Model) -> dict:
    systems = {}
    for s in model.systems.values():
        systems[s.database] = {
            "system": s.key,
            "service": s.service,
            "port": s.port,
            "mimics": s.mimics,
            "tables": len(s.tables),
            "columns": sum(len(t.columns) for t in s.tables),
            "foreign_keys": sum(1 for t in s.tables for c in t.columns if c.code_set or (c.ref and c.ref.enforced)),
            "soft_refs": sum(1 for t in s.tables for c in t.columns if c.ref and not c.ref.enforced),
            "ref_tables": len(s.code_sets),
            "partitioned_tables": [t.fqn for t in s.tables if t.partition_key],
        }
    return {"source_commit": model.source_sha, "systems": systems}
